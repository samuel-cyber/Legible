"""Report which constructs Channel B (the deterministic glyph layer) handles.

Reads the equations placed by build.py, runs the glyph layer on each bbox, and
diffs the result against the true LaTeX. Output is generated, never typed by
hand:

    py demo/hard/report.py

Writes demo/hard/REPORT.md and prints the same table.
"""
from __future__ import annotations

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)

from build import HARD_PDF, build  # noqa: E402
from equations.glyphs import glyph_tokens  # noqa: E402
from equations.tokens import diff, latex_to_tokens, spoken, to_text  # noqa: E402
from ingest.pdf import find_display_equations, load_page  # noqa: E402


def collect() -> tuple[list[dict], int]:
    placed = build()
    page = load_page(HARD_PDF, 0)
    rows = []
    for i, spec in enumerate(placed):
        gold = latex_to_tokens(spec["latex"])
        eq_id = f"p1e{i + 1}"
        try:
            got = glyph_tokens(page, spec["bbox"])
            problems = [d.explain() for d in diff(gold, got)]
        except Exception as e:  # noqa: BLE001
            got, problems = [], [f"glyph layer unavailable: {e}"]
        rows.append({
            "eq_id": eq_id,
            "id": spec["id"],
            "construct": spec["construct"],
            "latex": spec["latex"],
            "status": "verified" if not problems else "withheld",
            "expected": "verified" if spec["expected"] == "match" else "withheld",
            "differences": problems,
            "glyph_text": "".join(s for s, _ in got),
            "spoken": spoken(got) if got else "",
        })
    return rows, len(find_display_equations(page))


def to_markdown(rows: list[dict], regions: int) -> str:
    handled = [r for r in rows if r["status"] == "verified"]
    withheld = [r for r in rows if r["status"] == "withheld"]
    ok = all(r["status"] == r["expected"] for r in rows)

    lines = [
        "# Channel B on a harder page",
        "",
        "Generated by `py demo/hard/report.py`. The page (`hard.pdf`) has no LaTeX "
        "toolchain behind it: it is typeset directly with PyMuPDF so the glyph layer, "
        "baselines and fraction bars are real, and Channel B runs on it unmodified.",
        "",
        f"- Equations on the page: **{len(rows)}** (finder finds {regions} region(s))",
        f"- Reproduced exactly by Channel B: **{len(handled)}**",
        f"- Withheld (outside the token vocabulary): **{len(withheld)}**",
        f"- Channel B behaved as predicted for every equation: **{'yes' if ok else 'NO'}**",
        "",
        "| Eq | Construct | Channel B | Real LaTeX |",
        "| --- | --- | --- | --- |",
    ]
    for r in rows:
        mark = "verified" if r["status"] == "verified" else "withheld"
        lines.append(f"| {r['eq_id']} | {r['construct']} | {mark} | `{r['latex']}` |")

    lines += ["", "## Handled", ""]
    if handled:
        for r in handled:
            lines.append(f"- **{r['eq_id']}** - {r['construct']}: the reading and the "
                         f"glyph structure are token-for-token identical.")
    else:
        lines.append("- (none)")

    lines += ["", "## Withheld", ""]
    if withheld:
        for r in withheld:
            lines.append(f"- **{r['eq_id']}** - {r['construct']}. Channel B reads the "
                         f"glyphs as `{r['glyph_text']}` (spoken: \"{r['spoken']}\"), which "
                         f"cannot equal the transcription, so the equation is announced "
                         f"unverified rather than published as math.")
            for p in r["differences"]:
                lines.append(f"  - {p}")
    else:
        lines.append("- (none)")

    lines += [
        "",
        "## What this says about the scope",
        "",
        "Channel B needs the construct to be expressible as (symbol, context) tokens: "
        "bases, sub/superscripts, fractions (a horizontal rule with glyphs above and "
        "below) and accents. Summations, integrals, radicals and partial derivatives "
        "reduce to exactly those, so they verify. Binomial coefficients (two rows with "
        "no bar) and floor/ceiling brackets reduce to constructs the vocabulary has no "
        "token for, so they fail closed. Because Channel A is an independent reading, "
        "a wrong glyph reading, a wrong transcription, or a construct either channel "
        "cannot represent all end in the same place: **withheld, never published**.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    rows, regions = collect()
    md = to_markdown(rows, regions)
    out = os.path.join(HERE, "REPORT.md")
    with open(out, "w", encoding="utf-8") as f:
        f.write(md + "\n")
    print(md)
    print(f"\nwrote {out}")


if __name__ == "__main__":
    main()
